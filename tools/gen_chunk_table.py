#!/usr/bin/env python3
"""Generate src/chunk_table.c from recompiled/generated/generated.h.

DolRecomp emits `dolrecomp_call()` as a chain of ~450 range comparisons, which
costs hundreds of compares per dispatched block. Every chunk is a contiguous
0x4000-byte window (the first one excepted), so a direct-mapped table turns the
lookup into an index computation.

Run manually or via the CMake custom command (which passes the paths).
"""
import re
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_chunk_table.py <generated.h> <out.c>", file=sys.stderr)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()

    entries = re.findall(
        r"if \(address >= (0x[0-9A-Fa-f]+)u && address < (0x[0-9A-Fa-f]+)u"
        r".*?\{ (func_[0-9A-Fa-f]+)\(ctx\); return 1; \}",
        text,
    )
    if len(entries) < 2:
        print("error: no chunk entries found in %s" % src, file=sys.stderr)
        return 1

    first_base = int(entries[0][0], 16)
    first_end = int(entries[0][1], 16)
    first_fn = entries[0][2]

    table = entries[1:]
    base = int(table[0][0], 16)
    end = int(table[-1][1], 16)
    step = int(table[0][1], 16) - int(table[0][0], 16)

    for i, (b, e, _f) in enumerate(table):
        expect = base + i * step
        if int(b, 16) != expect:
            print(
                "error: chunk %d base 0x%X != expected 0x%X"
                % (i, int(b, 16), expect),
                file=sys.stderr,
            )
            return 1

    with open(dst, "w", encoding="utf-8") as out:
        out.write("// Generated by tools/gen_chunk_table.py -- do not edit.\n")
        out.write('#include "chunk_table.h"\n\n')
        out.write("#include \"generated.h\"\n\n")
        out.write("#define CHUNK_FIRST_BASE 0x%08Xu\n" % first_base)
        out.write("#define CHUNK_FIRST_END  0x%08Xu\n" % first_end)
        out.write("#define CHUNK_FIRST_FN    %s\n" % first_fn)
        out.write("#define CHUNK_BASE 0x%08Xu\n" % base)
        out.write("#define CHUNK_END  0x%08Xu\n" % end)
        out.write("#define CHUNK_COUNT %du\n\n" % len(table))
        out.write("typedef void (*ChunkFn)(CPUState*);\n\n")
        out.write("static ChunkFn const g_chunks[CHUNK_COUNT] = {\n")
        for _b, _e, fn in table:
            out.write("    %s,\n" % fn)
        out.write("};\n\n")
        out.write(
            """bool chunk_contains(u32 pc) {
    if (pc >= CHUNK_FIRST_BASE && pc < CHUNK_FIRST_END)
        return true;
    return pc >= CHUNK_BASE && pc < CHUNK_END;
}

bool chunk_dispatch(CPUState* cpu, u32 pc) {
    if (ppc_host_call(cpu, pc))
        return true;
    if (pc >= CHUNK_FIRST_BASE && pc < CHUNK_FIRST_END &&
        ((pc - CHUNK_FIRST_BASE) & 3u) == 0u) {
        CHUNK_FIRST_FN(cpu);
        return true;
    }
    if (pc >= CHUNK_BASE && pc < CHUNK_END && ((pc - CHUNK_BASE) & 3u) == 0u) {
        const u32 index = (pc - CHUNK_BASE) >> 14;
        if (index < CHUNK_COUNT) {
            g_chunks[index](cpu);
            return true;
        }
    }
    return false;
}
"""
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
